/** Port of the iOS `WalletTab` (mobile/ios/Moth/Views/HomeView.swift), without Cardano balances. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun HomeScreen(model: WalletModel, onReceive: () -> Unit, onSend: () -> Unit, onLogs: () -> Unit) {
    var confirmDeregister by remember { mutableStateOf(false) }
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Moth") },
                actions = {
                    IconButton(onClick = { model.refreshBalances() }) { Icon(Icons.Default.Refresh, "Refresh balances") }
                    IconButton(onClick = onLogs) { Icon(Icons.Default.Info, "Logs") }
                },
            )
        },
    ) { padding ->
        LazyColumn(Modifier.fillMaxSize().padding(padding).padding(horizontal = 16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
            item { SectionHeader("${model.walletName} · ${model.network}") }
            item { Card(Modifier.fillMaxWidth()) { SyncStatus(model) } }

            item { SectionHeader("Balances") }
            item { Card(Modifier.fillMaxWidth()) { Column(Modifier.padding(vertical = 4.dp)) { BalanceRows(model) } } }

            model.balances?.let { b ->
                item { SectionHeader("DUST") }
                item { Card(Modifier.fillMaxWidth()) { DustSummary(b) } }
                item {
                    // As iOS DustView: registering pays its own fee from DUST the NIGHT has already accrued.
                    val canAct = b.synced && !model.busy
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                        OutlinedButton(onClick = { model.registerDust() }, Modifier.weight(1f), enabled = canAct) { Text("Register NIGHT") }
                        if (b.dustGeneration?.registered == true) {
                            OutlinedButton(onClick = { confirmDeregister = true }, Modifier.weight(1f), enabled = canAct) { Text("Stop DUST") }
                        }
                    }
                }
                item {
                    Footnote("DUST pays Midnight transaction fees. It is generated by registered NIGHT and cNIGHT and can't be sent.")
                }
            }

            item {
                Row(Modifier.fillMaxWidth().padding(vertical = 8.dp), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    PrimaryButton("Receive", Modifier.weight(1f), enabled = model.addresses != null, onClick = onReceive)
                    PrimaryButton("Send", Modifier.weight(1f), enabled = model.addresses != null, onClick = onSend)
                }
            }
            item { Spacer(Modifier.size(24.dp)) }
        }
    }
    if (confirmDeregister) {
        AlertDialog(
            onDismissRequest = { confirmDeregister = false },
            title = { Text("Stop generating DUST?") },
            text = { Text("This account's NIGHT stops generating DUST. The transaction pays a DUST fee.") },
            confirmButton = { TextButton(onClick = { confirmDeregister = false; model.deregisterDust() }) { Text("Deregister and pay fee") } },
            dismissButton = { TextButton(onClick = { confirmDeregister = false }) { Text("Cancel") } },
        )
    }
}

@Composable
private fun SyncStatus(model: WalletModel) {
    val b = model.balances
    Row(Modifier.padding(16.dp), verticalAlignment = Alignment.CenterVertically) {
        if (b?.synced == true) {
            Icon(Icons.Default.CheckCircle, null, tint = MaterialTheme.colorScheme.primary)
        } else {
            CircularProgressIndicator(Modifier.size(22.dp), strokeWidth = 2.5.dp)
        }
        Spacer(Modifier.width(12.dp))
        Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
            val text = when (model.phase) {
                WalletModel.Phase.Starting -> "Starting the wallet engine…"
                WalletModel.Phase.Unlocking -> "Unlocking…"
                // moth's progress line ("syncing 20% (dust) — shielded 100%, …") repeats the bars;
                // keep only its time estimate.
                else -> if (model.status.startsWith("syncing")) {
                    Regex("""\(([^)]*) remaining\)""").find(model.status)?.let { "Syncing · about ${it.groupValues[1]} left" } ?: "Syncing…"
                } else {
                    model.status.ifEmpty { "Syncing…" }
                }
            }
            Text(text, style = MaterialTheme.typography.bodyMedium, maxLines = 2)
            if (b != null && !b.synced) {
                b.progress.forEach { (name, p) ->
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text(name, Modifier.width(92.dp), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                        LinearProgressIndicator(progress = { (p ?: 0.0).toFloat() }, Modifier.weight(1f))
                        Text(
                            p?.let { "${(it * 100).toInt()}%" } ?: "–",
                            Modifier.width(48.dp),
                            style = MaterialTheme.typography.bodySmall,
                            fontFamily = FontFamily.Monospace,
                            textAlign = androidx.compose.ui.text.style.TextAlign.End,
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun BalanceRows(model: WalletModel) {
    val b = model.balances
    val night = model.addresses?.nightTokenId
    if (b == null || night == null) {
        Text("Waiting for the first sync update…", Modifier.padding(16.dp), color = MaterialTheme.colorScheme.onSurfaceVariant)
        return
    }
    val nightAmount = { base: String? -> Amount.format(base ?: "0", Amount.NIGHT_DECIMALS, 6) }
    BalanceRow("NIGHT", "unshielded", nightAmount(b.unshielded[night]))
    b.unshielded.keys.filter { it != night }.sorted().forEach { id ->
        HorizontalDivider()
        BalanceRow(tokenLabel(id), "unshielded token", b.unshielded[id] ?: "0")
    }
    b.shielded.keys.sorted().forEach { id ->
        HorizontalDivider()
        if (id == night) BalanceRow("NIGHT", "shielded", nightAmount(b.shielded[id]))
        else BalanceRow(tokenLabel(id), "shielded", b.shielded[id] ?: "0")
    }
}

@Composable
private fun BalanceRow(name: String, detail: String, amount: String) {
    Row(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 10.dp), verticalAlignment = Alignment.CenterVertically) {
        Column(Modifier.weight(1f)) {
            Text(name, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.SemiBold)
            Text(detail, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
        Text(amount, fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.bodyLarge)
    }
}

/** DUST balance against its capacity, and what generates it. */
@Composable
private fun DustSummary(b: Balances) {
    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Text("DUST", Modifier.weight(1f), style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.SemiBold)
            Text(Amount.format(b.dust, Amount.DUST_DECIMALS, 6), fontFamily = FontFamily.Monospace)
        }
        val g = b.dustGeneration
        val limit = g?.limit?.toBigDecimalOrNull()
        if (g != null && g.registered && limit != null && limit.signum() > 0) {
            val dust = b.dust.toBigDecimalOrNull() ?: java.math.BigDecimal.ZERO
            val used = (dust.toDouble() / limit.toDouble()).coerceIn(0.0, 1.0)
            LinearProgressIndicator(progress = { used.toFloat() }, Modifier.fillMaxWidth())
            Detail("Max capacity", Amount.format(g.limit, Amount.DUST_DECIMALS, 3) + " DUST")
            Detail("Generating", Amount.format(g.ratePerDay, Amount.DUST_DECIMALS, 3) + " DUST a day")
            val fill = g.fillTime
            if (fill != null && fill * 1000 > System.currentTimeMillis() && dust < limit) {
                Detail("Full", DateUtils.getRelativeTimeSpanString((fill * 1000).toLong()).toString())
            }
            Detail("Backed by this account", Amount.format(g.registeredNight, Amount.NIGHT_DECIMALS, 2) + " NIGHT")
            val others = Amount.minus(g.designated, g.registeredNight)
            if (others != null && others.signum() > 0) {
                Detail("Backed by cNIGHT or other accounts", Amount.format(others.toString(), Amount.NIGHT_DECIMALS, 2) + " NIGHT")
            }
        } else {
            Text(
                "Not generating. Register NIGHT or cNIGHT to generate DUST.",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }
}

@Composable
private fun Detail(label: String, value: String) {
    Row {
        Text(label, Modifier.weight(1f), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Text(value, style = MaterialTheme.typography.bodySmall, fontFamily = FontFamily.Monospace)
    }
}

@Composable
fun SectionHeader(text: String) {
    Text(
        text.uppercase(),
        Modifier.padding(start = 4.dp, top = 8.dp),
        style = MaterialTheme.typography.labelMedium,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
    )
}

@Composable
fun Footnote(text: String) {
    Text(text, Modifier.padding(horizontal = 4.dp), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
}

@Suppress("unused")
private fun LazyListScope.spacer() = item { Spacer(Modifier.size(8.dp)) }
