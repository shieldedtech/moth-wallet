/// The unlocked app: wallet, activity, DApp browser and settings, with DApp approvals on top.
struct HomeView: View {
    @EnvironmentObject private var model: WalletModel

    var body: some View {
        TabView {
            WalletTab().tabItem { Label("Wallet", systemImage: "wallet.bifold") }
            ActivityView().tabItem { Label("Activity", systemImage: "clock") }
            BrowserView().tabItem { Label("Browser", systemImage: "globe") }
            SettingsView().tabItem { Label("Settings", systemImage: "gearshape") }
