}

private struct WalletTab: View {
    @EnvironmentObject private var model: WalletModel
    @State private var sheet: Sheet?

    enum Sheet: Identifiable {
        case receive
        /// Send, opened on a chain and, from a balance row, on that asset.
        case send(chain: String, kind: Transfer.Kind = .unshielded, token: String? = nil)

        var id: String {
            switch self {
            case .receive: "receive"
            case let .send(chain, kind, token): "send-\(chain)-\(kind.rawValue)-\(token ?? "")"
            }
        }
    }

    var body: some View {
        NavigationStack {
            List {
                Section {
                    SyncStatus()
                } header: {
                    Text("\(model.active?.title ?? "") · \(model.network)")
                }
                Section("Balances") {
                    if let b = model.balances, let night = model.addresses?.nightTokenId {
                        Button { sheet = .send(chain: "midnight", kind: .unshielded, token: night) } label: {
                            BalanceRow(name: "NIGHT", detail: "unshielded",
                                       amount: Amount.format(b.unshielded[night] ?? "0", decimals: Amount.nightDecimals, places: 6))
                        }
                        .buttonStyle(BalanceButtonStyle())
                        ForEach(b.unshielded.keys.filter { $0 != night }.sorted(), id: \.self) { id in
                            Button { sheet = .send(chain: "midnight", kind: .unshielded, token: id) } label: {
                                BalanceRow(name: Token.label(id), detail: "unshielded token", amount: b.unshielded[id] ?? "0")
                            }
                            .buttonStyle(BalanceButtonStyle())
                        }
                        ForEach(b.shielded.keys.sorted(), id: \.self) { id in
                            Button { sheet = .send(chain: "midnight", kind: .shielded, token: id) } label: {
                                BalanceRow(name: id == night ? "NIGHT" : Token.label(id), detail: "shielded",
                                           amount: id == night ? Amount.format(b.shielded[id] ?? "0", decimals: Amount.nightDecimals, places: 6) : b.shielded[id] ?? "0")
                            }
                            .buttonStyle(BalanceButtonStyle())
                        }
                        if let cardano = model.cardano {
                            Button { sheet = .send(chain: "cardano") } label: {
                                BalanceRow(name: "cNIGHT", detail: cardano.registered ? "Cardano · generating DUST" : "Cardano",
                                           amount: Amount.format(cardano.cnight, decimals: Amount.nightDecimals, places: 6))
                            }
                            .buttonStyle(BalanceButtonStyle())
                            Button { sheet = .send(chain: "cardano") } label: {
                                BalanceRow(name: "ADA", detail: "Cardano",
                                           amount: Amount.format(cardano.lovelace, decimals: Amount.adaDecimals, places: 6))
                            }
                            .buttonStyle(BalanceButtonStyle())
                        } else if let problem = model.cardanoProblem {
                            VStack(alignment: .leading, spacing: 2) {
                                Text("cNIGHT · ADA").font(.headline)
                                Text(problem).font(.caption).foregroundStyle(.secondary)
                            }
                        }
                    } else {
                        Text("Waiting for the first sync update…").foregroundStyle(.secondary)
                    }
                }
                if let b = model.balances {
                    Section {
                        DustSummary(balances: b)
                    } header: {
                        Text("DUST")
                    } footer: {
                        Text("DUST pays Midnight transaction fees. It is generated by registered NIGHT and cNIGHT and can't be sent.")
                    }
                }
                Section {
                    Button { sheet = .receive } label: { Label("Receive", systemImage: "arrow.down.circle") }
                    Button { sheet = .send(chain: "midnight") } label: { Label("Send", systemImage: "arrow.up.circle") }
                    NavigationLink { DustView() } label: { Label("Generate DUST from NIGHT", systemImage: "sparkles") }
                    NavigationLink { CardanoView() } label: { Label("Generate DUST from cNIGHT", systemImage: "link") }
                }
            }
            .navigationTitle("Moth")
            .refreshable { await model.refreshCardano() }
            .task(id: "\(model.activeName)/\(model.network)/\(model.blockfrostProjectId != nil)") { await model.refreshCardano() }
            .toolbar {
                ToolbarItem(placement: .topBarTrailing) {
                    Button { Task { await model.lock() } } label: { Image(systemName: "lock") }
                        .accessibilityLabel("Lock")
                }
            }
            .sheet(item: $sheet) { sheet in
                switch sheet {
                case .receive: ReceiveView()
                case let .send(chain, kind, token): SendView(chain: chain, kind: kind, token: token)
                }
            }
        }
    }
}

enum Clipboard {
    /// Copies to this device only (no Universal Clipboard), cleared after two minutes.
    static func copy(_ text: String) {
        UIPasteboard.general.setItems([[UTType.plainText.identifier: text]],
                                      options: [.localOnly: true, .expirationDate: Date().addingTimeInterval(120)])
    }
}

enum Token {
    /// Tokens other than NIGHT have no registry yet, so they are shown by a short id.
    static func label(_ id: String) -> String { "\(id.prefix(8))…" }
}

private struct SyncStatus: View {
    @EnvironmentObject private var model: WalletModel

    var body: some View {
        HStack(spacing: 12) {
            if model.balances?.synced == true {
                Image(systemName: "checkmark.circle.fill").foregroundStyle(Theme.accent)
            } else {
                ProgressView()
            }
            VStack(alignment: .leading, spacing: 4) {
                Text(model.status.isEmpty ? "Syncing…" : model.status).font(.subheadline).lineLimit(2)
                if model.balances?.synced != true, let p = model.balances?.progress {
                    ProgressView(value: p).tint(Theme.accent)
                }
            }
        }
    }
}

