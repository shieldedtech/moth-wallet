    func makeBody(configuration: Configuration) -> some View {
        configuration.label.opacity(configuration.isPressed ? 0.5 : 1)
    }
}

/// DUST balance against its capacity, and what generates it.
private struct DustSummary: View {
    let balances: Balances

    var body: some View {
        let generation = balances.dustGeneration
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                Text("DUST").font(.headline)
                Spacer()
                Text(Amount.format(balances.dust, decimals: Amount.dustDecimals, places: 6)).font(.body.monospacedDigit())
            }
            if let g = generation, g.registered, let limit = Double(g.limit), limit > 0 {
                ProgressView(value: min(1, (Double(balances.dust) ?? 0) / limit)).tint(Theme.accent)
                    .accessibilityLabel("DUST capacity used")
                detail("Max capacity", Amount.format(g.limit, decimals: Amount.dustDecimals, places: 3) + " DUST")
                detail("Generating", Amount.format(g.ratePerDay, decimals: Amount.dustDecimals, places: 3) + " DUST a day")
                if let fill = g.fillTime, fill > Date().timeIntervalSince1970, (Double(balances.dust) ?? 0) < limit {
                    HStack {
                        Text("Full").foregroundStyle(.secondary)
                        Spacer()
                        Text(Date(timeIntervalSince1970: fill), style: .relative)
                    }
                    .font(.caption)
                }
                detail("Backed by this account", Amount.format(g.registeredNight, decimals: Amount.nightDecimals, places: 2) + " NIGHT")
                if let others = backingFromElsewhere(g), others != "0" {
                    detail("Backed by cNIGHT or other accounts", Amount.format(others, decimals: Amount.nightDecimals, places: 2) + " NIGHT")
                }
            } else {
                Text("Not generating. Register NIGHT or cNIGHT below to generate DUST.").font(.caption).foregroundStyle(.secondary)
            }
        }
    }

    private func detail(_ label: String, _ value: String) -> some View {
        HStack {
            Text(label).foregroundStyle(.secondary)
            Spacer()
            Text(value).monospacedDigit()
        }
        .font(.caption)
    }

    /// NIGHT-equivalent backing beyond this account's own registered NIGHT, in STAR.
    private func backingFromElsewhere(_ g: Balances.DustGeneration) -> String? {
        guard let designated = Decimal(string: g.designated), let own = Decimal(string: g.registeredNight), designated > own else { return nil }
        return NSDecimalNumber(decimal: designated - own).stringValue
    }
}

struct ReceiveView: View {
    @EnvironmentObject private var model: WalletModel
    @Environment(\.dismiss) private var dismiss
    @State private var kind = "unshielded"
    @State private var cardanoAddress: String?
    @State private var cardanoError: String?

    var body: some View {
        NavigationStack {
            VStack(spacing: 20) {
                Picker("Address", selection: $kind) {
                    Text("Unshielded").tag("unshielded")
                    Text("Shielded").tag("shielded")
                    Text("DUST").tag("dust")
                    Text("Cardano").tag("cardano")
                }
                .pickerStyle(.segmented)
                if kind == "dust" {
                    Text("Give this to someone registering NIGHT or cNIGHT, so its DUST is generated for this account.")
                        .font(.footnote).foregroundStyle(.secondary).multilineTextAlignment(.center)
                }
                if kind == "cardano" {
                    Text("Receives ADA and cNIGHT on Cardano \(model.cardanoNetwork), from the same recovery phrase.")
                        .font(.footnote).foregroundStyle(.secondary).multilineTextAlignment(.center)
                    if let cardanoError {
                        Text(cardanoError).font(.footnote).foregroundStyle(.orange).multilineTextAlignment(.center)
                    }
                }
                if let address {
                    QRCode(text: address).frame(width: 240, height: 240)
                    Text(address).font(.caption.monospaced()).textSelection(.enabled).multilineTextAlignment(.center)
                    Button { Clipboard.copy(address) } label: { Label("Copy address", systemImage: "doc.on.doc") }
                        .buttonStyle(PrimaryButton())
                }
                Spacer()
            }
            .padding(24)
            .task(id: kind) {
                guard kind == "cardano", cardanoAddress == nil else { return }
                do {
                    cardanoAddress = try await model.cardanoAddress()
                } catch {
                    cardanoError = error.localizedDescription
                }
            }
            .navigationTitle("Receive")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar { ToolbarItem(placement: .confirmationAction) { Button("Done") { dismiss() } } }
        }
    }

    private var address: String? {
        switch kind {
        case "shielded": model.addresses?.shielded
        case "dust": model.addresses?.dust
        case "cardano": cardanoAddress
        default: model.addresses?.unshielded
        }
    }
}

private struct QRCode: View {
    let text: String

    var body: some View {
        if let image {
            Image(uiImage: image).interpolation(.none).resizable().scaledToFit()
        }
    }

    private var image: UIImage? {
        let filter = CIFilter.qrCodeGenerator()
        filter.message = Data(text.utf8)
        filter.correctionLevel = "M"
        guard let output = filter.outputImage?.transformed(by: CGAffineTransform(scaleX: 8, y: 8)),
              let cg = CIContext().createCGImage(output, from: output.extent) else { return nil }
        return UIImage(cgImage: cg)
    }
}

/// One recipient in a send: what, how much, to whom.
private struct SendLine: Identifiable, Equatable {
    let id = UUID()
    var kind = Transfer.Kind.unshielded
    var token: String?
    var to = ""
    var amount = ""
}

struct SendView: View {
    @EnvironmentObject private var model: WalletModel
    @Environment(\.dismiss) private var dismiss
    @State private var chain: String
    @State private var lines: [SendLine]

    init(chain: String = "midnight", kind: Transfer.Kind = .unshielded, token: String? = nil) {
        _chain = State(initialValue: chain)
        _lines = State(initialValue: [SendLine(kind: kind, token: token)])
    }
    @State private var fee: String?
    @State private var sentHash: String?
    @State private var pickingContactFor: UUID?

    var body: some View {
        NavigationStack {
            Group {
                if chain == "cardano" {
                    CardanoSendForm(registered: model.cardano?.registered == true, sentHash: $sentHash)
                } else {
                    midnightForm
                }
            }
            .safeAreaInset(edge: .top) {
                Picker("Network", selection: $chain) {
                    Text("Midnight").tag("midnight")
                    Text("Cardano").tag("cardano")
                }
                .pickerStyle(.segmented)
                .padding(.horizontal)
                .padding(.vertical, 8)
                .background(.bar)
                .disabled(sentHash != nil)
            }
            .navigationTitle("Send")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) { Button(sentHash == nil ? "Cancel" : "Done") { dismiss() } }
            }
        }
    }

    private var midnightForm: some View {
            Form {
                if model.balances?.synced != true {
                    Section { Text("Waiting for Midnight to finish syncing.").foregroundStyle(.secondary) }
                }
                ForEach($lines) { $line in
                    Section {
                        Picker("Kind", selection: $line.kind) {
                            Text("Unshielded").tag(Transfer.Kind.unshielded)
                            Text("Shielded").tag(Transfer.Kind.shielded)
                        }
                        .pickerStyle(.segmented)
                        let held = tokens(line.kind)
                        if held.isEmpty {
                            Text("No \(line.kind.rawValue) tokens held.").foregroundStyle(.secondary)
                        } else {
                            Picker("Token", selection: $line.token) {
                                ForEach(held, id: \.self) { id in
                                    Text("\(name(id)) — \(heldAmount(id, line.kind))").tag(Optional(id))
                                }
                            }
                        }
                        HStack {
                            TextField(line.kind == .unshielded ? "mn_addr…" : "mn_shield-addr…", text: $line.to, axis: .vertical)
                                .font(.body.monospaced())
                                .textInputAutocapitalization(.never)
                                .autocorrectionDisabled()
                            Button { pickingContactFor = line.id } label: { Image(systemName: "person.crop.circle") }
                                .accessibilityLabel("Choose a contact")
                        }
                        TextField(isNight(line) ? "Amount in NIGHT" : "Amount in base units", text: $line.amount)
                            .keyboardType(isNight(line) ? .decimalPad : .numberPad)
                    } header: {
                        HStack {
                            Text(lines.count > 1 ? "Recipient \((lines.firstIndex(of: line) ?? 0) + 1)" : "Recipient")
                            Spacer()
                            if lines.count > 1 {
                                Button("Remove", role: .destructive) { lines.removeAll { $0.id == line.id } }
                                    .font(.caption)
                            }
                        }
                    }
                    .onAppear { if line.token == nil { line.token = tokens(line.kind).first } }
                    .onChange(of: line.kind) { line.token = tokens(line.kind).first }
                }
                Section {
                    Button { lines.append(SendLine(token: tokens(.unshielded).first)) } label: { Label("Add recipient", systemImage: "plus") }
                } footer: {
                    if let fee {
                        Text("Fee for the whole transaction: \(Amount.format(fee, decimals: Amount.dustDecimals, places: 6)) DUST")
                    } else if lines.count > 1 {
                        Text("All recipients are paid in one transaction, with one fee.")
                    }
                }
                if let sentHash {
                    Section("Submitted") { Text(sentHash).font(.caption.monospaced()).textSelection(.enabled) }
                }
            }
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button(model.busy ? "Working…" : fee == nil ? "Review" : "Send") { Task { await send() } }
                        .disabled(!ready || model.busy || sentHash != nil || model.balances?.synced != true)
                }
            }
            .onChange(of: lines) { fee = nil }
            .sheet(item: Binding(get: { pickingContactFor.map { PickTarget(id: $0) } }, set: { pickingContactFor = $0?.id })) { target in
                ContactPicker { contact in
                    if let index = lines.firstIndex(where: { $0.id == target.id }) {
                        lines[index].to = contact.address
                        if contact.kind == "shielded" { lines[index].kind = .shielded }
                        if contact.kind == "unshielded" { lines[index].kind = .unshielded }
                    }
                }
            }
    }

    private struct PickTarget: Identifiable { let id: UUID }

    private var ready: Bool {
        !lines.isEmpty && lines.allSatisfy { $0.token != nil && !$0.to.trimmingCharacters(in: .whitespaces).isEmpty && !$0.amount.isEmpty }
    }

    /// Tokens held of a kind, NIGHT first.
    private func tokens(_ kind: Transfer.Kind) -> [String] {
        let held = (kind == .unshielded ? model.balances?.unshielded : model.balances?.shielded) ?? [:]
        let night = model.addresses?.nightTokenId
        return held.keys.sorted { ($0 == night ? 0 : 1, $0) < ($1 == night ? 0 : 1, $1) }
    }

    private func isNight(_ line: SendLine) -> Bool { line.token != nil && line.token == model.addresses?.nightTokenId }

    private func name(_ id: String) -> String { id == model.addresses?.nightTokenId ? "NIGHT" : Token.label(id) }

    private func heldAmount(_ id: String, _ kind: Transfer.Kind) -> String {
        let base = (kind == .unshielded ? model.balances?.unshielded[id] : model.balances?.shielded[id]) ?? "0"
        return id == model.addresses?.nightTokenId ? Amount.format(base, decimals: Amount.nightDecimals, places: 6) : base
    }

    private func send() async {
        do {
            var transfers: [Transfer] = []
            for line in lines {
                guard let token = line.token else { return }
                let base = try await model.baseUnits(line.amount, tokenId: token)
                transfers.append(Transfer(kind: line.kind, tokenId: token, amount: base, to: line.to.trimmingCharacters(in: .whitespacesAndNewlines)))
            }
            // The first tap shows the fee; the second sends.
            guard fee != nil else {
                fee = try await model.estimateFee(transfers)
                return
            }
            sentHash = try await model.send(transfers)
        } catch {
            model.error = error.localizedDescription
        }
    }
}
